def get_current_lang() -> str:
    try:
        settings = get_settings()
        return settings.get("language", "en")
    except Exception:
        return "en"

def set_current_lang(lang: str):
    if lang in I18N_DATA:
        try:
            save_settings({"language": lang})
        except Exception:
            pass

def t(key: str, lang: str = None) -> str:
    if not lang:
        lang = get_current_lang()
    lang_dict = I18N_DATA.get(lang, I18N_DATA["en"])
    return lang_dict.get(key, I18N_DATA["en"].get(key, key))
